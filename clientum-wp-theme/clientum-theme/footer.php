  document.querySelectorAll('.faq-question').forEach(function(q) {
    q.addEventListener('click', function() {
      var item = this.closest('.faq-item');
      document.querySelectorAll('.faq-item.open').forEach(function(o) {
        if (o !== item) o.classList.remove('open');
      });
      item.classList.toggle('open');
    });
  });

  /* ── Filter tabs ──────────────────────────────────────────────────────── */
  document.querySelectorAll('.filter-tab').forEach(function(tab) {
    tab.addEventListener('click', function() {
      var parent = this.closest('.filter-tabs');
      parent.querySelectorAll('.filter-tab').forEach(function(t) { t.classList.remove('active'); });
      this.classList.add('active');
      var filter = this.dataset.filter;
      var cards  = document.querySelectorAll('.project-card[data-industry]');
      cards.forEach(function(card) {
        if (filter === 'all' || card.dataset.industry === filter) {
          card.style.display = '';
        } else {
          card.style.display = 'none';
        }
      });
    });
  });

  /* ── Toast helper ─────────────────────────────────────────────────────── */
  window.clientumToast = function(msg, type) {
    var toast = document.getElementById('site-toast');
    if (!toast) return;
    toast.innerHTML = '<svg xmlns="http://www.w3.org/2000/svg" width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><polyline points="20 6 9 17 4 12"/></svg> ' + msg;
    toast.className = 'toast show' + (type ? ' ' + type : '');
    setTimeout(function() { toast.className = 'toast'; }, 4000);
  };

  /* ── Hero demo form (AJAX) ────────────────────────────────────────────── */
  var demoForm = document.getElementById('hero-demo-form');
  if (demoForm) {
    demoForm.addEventListener('submit', function(e) {
      e.preventDefault();
      var btn  = this.querySelector('.btn-submit');
      var orig = btn.textContent;
      btn.textContent = 'Enviando...';
      btn.disabled = true;

      var data = new FormData(this);
      data.append('action',  'clientum_demo_request');
      data.append('nonce',   clientumData.nonce);

      fetch(clientumData.ajaxUrl, { method: 'POST', body: data })
        .then(function(r) { return r.json(); })
        .then(function(res) {
          if (res.success) {
            demoForm.reset();
            window.clientumToast('¡Solicitud enviada! Te contactamos en menos de 24h.', 'success');
          } else {
            window.clientumToast('Error al enviar. Intentá de nuevo.', '');
          }
        })
        .catch(function() {
          window.clientumToast('Error de conexión. Intentá de nuevo.', '');
        })
        .finally(function() {
          btn.textContent = orig;
          btn.disabled = false;
        });
    });
  }

